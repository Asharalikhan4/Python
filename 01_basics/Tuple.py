'''
- Tuples are very similar to list except they are immutable in nature.
- Symbol - ()
'''

tup = ()
print("Tuple", tup)

# Using String
tup = ('Geeks', 'For')
print("Tuple Using String", tup)

# Using List
li = [1, 2, 4, 5, 6]
print("Using List", tuple(li))

# Using Built-in Function
tup = tuple('Geeks')
print("Using Built-in function", tup)